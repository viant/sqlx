func pgRows(width int, values ...[]driver.Value) driver.Rows {
	columns := make([]string, width)
	for i := range columns {
		columns[i] = fmt.Sprintf("c%d", i)
	}
	return nativeRows(columns, values...)
}
func pgColumnRow(name, typ string, notNull bool, defaultSQL, identity, generated string) []driver.Value {
	return []driver.Value{name, typ, notNull, defaultSQL, identity, generated, "", "pg_catalog", false, ""}
}

func TestPostgreSQLNativeCatalogReconstruction(t *testing.T) {
	var partitioned bool
	db := sql.OpenDB(schemaConnector{query: func(q string, args []driver.NamedValue) (driver.Rows, error) {
		switch {
		case strings.Contains(q, "server_version_num"):
			return pgRows(1, []driver.Value{int64(160000)}), nil
		case strings.HasPrefix(q, "SELECT c.oid::bigint"):
			require.Equal(t, "public", args[0].Value)
			oid := int64(11)
			if args[1].Value == "parent" {
				oid = 22
			}
			return pgRows(10, []driver.Value{oid, "r", "p", partitioned, false, false, "", false, "heap", false}), nil
		case strings.HasPrefix(q, "SELECT a.attname,pg_catalog.format_type"):
			if args[0].Value == int64(22) {
				return pgRows(10, pgColumnRow("id", "bigint", true, `nextval('public.parent_id_seq'::regclass)`, "", ""), pgColumnRow("key", "text", true, `'x;y'::text`, "", "")), nil
			}
			return pgRows(10, pgColumnRow("id", "bigint", true, "", "d", ""), pgColumnRow("parent", "bigint", true, "22", "", ""), pgColumnRow("key", "text", true, `'x;y'::text`, "", ""), pgColumnRow("amount", "numeric(12,4)", true, "12.3456", "", ""), pgColumnRow("computed", "numeric", false, "amount * 2", "", "s")), nil
		case strings.HasPrefix(q, "SELECT a.attname,n.nspname,s.relname"):
			if args[0].Value == int64(22) {
				return pgRows(12, []driver.Value{"id", "public", "parent_id_seq", "a", "bigint", "p", int64(1), int64(1), int64(1), int64(9223372036854775807), int64(1), false}), nil
			}
			return pgRows(12, []driver.Value{"id", "public", "child_id_seq", "i", "bigint", "p", int64(5), int64(2), int64(1), int64(9223372036854775807), int64(10), false}), nil
		case strings.HasPrefix(q, "SELECT DISTINCT n.nspname,s.relname"):
			if args[0].Value == int64(22) {
				return pgRows(2, []driver.Value{"public", "parent_id_seq"}), nil
			}
			return pgRows(2), nil
		case strings.HasPrefix(q, "WITH objects AS"):
			return pgRows(1, []driver.Value{false}), nil
		case strings.HasPrefix(q, "SELECT c.conname"):
			if args[0].Value == int64(22) {
				return pgRows(5, []driver.Value{"parent_pk", "p", `PRIMARY KEY (id, key)`, "", ""}), nil
			}
			return pgRows(5, []driver.Value{"child_pk", "p", `PRIMARY KEY (id)`, "", ""}, []driver.Value{"parent_fk", "f", `FOREIGN KEY (parent, key) REFERENCES public.parent(id, key) DEFERRABLE INITIALLY DEFERRED`, "public", "parent"}, []driver.Value{"positive", "c", `CHECK (amount >= 0::numeric)`, "", ""}), nil
		case strings.HasPrefix(q, "SELECT ci.relname"):
			if args[0].Value == int64(22) {
				return pgRows(4), nil
			}
			return pgRows(4, []driver.Value{"child.amount", `CREATE UNIQUE INDEX "child.amount" ON public.child USING btree (amount) WHERE amount > 0::numeric`, true, "btree"}), nil
		case strings.HasPrefix(q, "SELECT last_value,is_called"):
			return pgRows(2, []driver.Value{int64(99), true}), nil
		default:
			t.Fatalf("unexpected PostgreSQL query %s", q)
			return nil, nil
		}
	}})
	defer db.Close()
	opts := ExtractOptions{Dialect: &info.Dialect{Product: database.Product{Name: "PostgreSQL", Major: 14}}, Schema: "public", Tables: []string{"child"}, IncludeDependencies: true}
	artifact, err := Extract(context.Background(), db, opts)
	require.NoError(t, err)
	require.True(t, artifact.Complete)
	require.Equal(t, []string{"parent", "child"}, artifact.Tables)
	sqlText := artifact.SQL()
	require.Contains(t, sqlText, `CREATE SEQUENCE "public"."parent_id_seq" AS bigint START WITH 1 INCREMENT BY 1`)
	require.Contains(t, sqlText, `"id" bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME "public"."child_id_seq" START WITH 5 INCREMENT BY 2`)
	require.Contains(t, sqlText, `"amount" numeric(12,4) DEFAULT 12.3456 NOT NULL`)
	require.Contains(t, sqlText, `"computed" numeric GENERATED ALWAYS AS (amount * 2) STORED`)
	require.Contains(t, sqlText, `CONSTRAINT "parent_pk" PRIMARY KEY (id, key)`)
	require.Contains(t, sqlText, `ALTER TABLE "public"."child" ADD CONSTRAINT "parent_fk" FOREIGN KEY (parent, key) REFERENCES public.parent(id, key) DEFERRABLE INITIALLY DEFERRED`)
	require.Contains(t, sqlText, `ALTER SEQUENCE "public"."parent_id_seq" OWNED BY "public"."parent"."id"`)
	require.NotContains(t, sqlText, "setval")
	statements, err := SplitSQL(sqlText, "PostgreSQL")
	require.NoError(t, err)
	require.Len(t, statements, len(artifact.Statements))
	opts.IncludeSequenceState = true
	withState, err := Extract(context.Background(), db, opts)
	require.NoError(t, err)
	require.Len(t, withState.Statements, len(artifact.Statements)+2)
	require.Contains(t, withState.SQL(), `pg_catalog.setval('"public"."child_id_seq"'::pg_catalog.regclass,99,true)`)
	opts.IncludeDependencies = false
	_, err = Extract(context.Background(), db, opts)
	require.ErrorContains(t, err, "requires unselected")
	opts.IncludeDependencies = true
	partitioned = true
	partial, err := Extract(context.Background(), db, opts)
	require.ErrorIs(t, err, ErrUnsupported)
	require.False(t, partial.Complete)
	require.Empty(t, partial.Statements)
	opts.AllowPartial = true
	partial, err = Extract(context.Background(), db, opts)
	require.NoError(t, err)
	require.NotEmpty(t, partial.Omissions)
}
