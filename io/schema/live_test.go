// These opt-in tests create and drop two uniquely named databases using the
// explicitly supplied admin DSN. They never reuse an existing database.
func TestLivePostgreSQLSchemaRoundTrip(t *testing.T) {
	dsn := os.Getenv("SQLX_SCHEMA_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set SQLX_SCHEMA_POSTGRES_DSN to an isolated PostgreSQL 14+ admin URL")
	}
	parsed, err := url.Parse(dsn)
	require.NoError(t, err)
	d := &info.Dialect{Product: database.Product{Name: "PostgreSQL", Major: 14}}
	source, target, sourceName, targetName := liveSchemaDBs(t, "postgres", dsn, d, func(name string) string { u := *parsed; u.Path = "/" + name; return u.String() })
	_ = sourceName
	_ = targetName
	liveSchemaRoundTrip(t, source, target, d, "public", "public")
}

func TestLiveMySQLSchemaRoundTrip(t *testing.T) {
	dsn := os.Getenv("SQLX_SCHEMA_MYSQL_DSN")
	if dsn == "" {
		t.Skip("set SQLX_SCHEMA_MYSQL_DSN to an isolated MySQL 8 admin DSN")
	}
	parsed, err := mysqlDriver.ParseDSN(dsn)
	require.NoError(t, err)
	d := &info.Dialect{Product: database.Product{Name: "MySQL", Major: 8}}
	source, target, sourceName, targetName := liveSchemaDBs(t, "mysql", dsn, d, func(name string) string { config := *parsed; config.DBName = name; return config.FormatDSN() })
	liveSchemaRoundTrip(t, source, target, d, sourceName, targetName)
}

func liveSchemaDBs(t *testing.T, driverName, adminDSN string, d *info.Dialect, dsnFor func(string) string) (*sql.DB, *sql.DB, string, string) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	t.Cleanup(cancel)
	admin, err := sql.Open(driverName, adminDSN)
	require.NoError(t, err)
	t.Cleanup(func() { _ = admin.Close() })
	require.NoError(t, admin.PingContext(ctx))
	suffix := fmt.Sprintf("%d", time.Now().UnixNano())
	names := []string{"sqlx_schema_source_" + suffix, "sqlx_schema_target_" + suffix}
	var dbs []*sql.DB
	for _, name := range names {
		quoted, err := d.QuoteIdentifier(name)
		require.NoError(t, err)
		_, err = admin.ExecContext(ctx, "CREATE DATABASE "+quoted)
		require.NoError(t, err)
		t.Cleanup(func() {
			cleanup, cancel := context.WithTimeout(context.Background(), 15*time.Second)
			defer cancel()
			_, err := admin.ExecContext(cleanup, "DROP DATABASE "+quoted)
			if err != nil {
				t.Errorf("drop isolated schema database: %v", err)
			}
		})
		db, err := sql.Open(driverName, dsnFor(name))
		require.NoError(t, err)
		t.Cleanup(func() { _ = db.Close() })
		require.NoError(t, db.PingContext(ctx))
		dbs = append(dbs, db)
	}
	return dbs[0], dbs[1], names[0], names[1]
}

func liveSchemaRoundTrip(t *testing.T, source, target *sql.DB, d *info.Dialect, sourceSchema, targetSchema string) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	defer cancel()
	q := func(name string) string {
		quoted, err := d.QuoteIdentifier(name)
		require.NoError(t, err)
		return quoted
	}
	identity := "BIGINT GENERATED BY DEFAULT AS IDENTITY"
	childID := "BIGSERIAL"
	pg := strings.EqualFold(d.Name, "PostgreSQL")
	if !pg {
		identity = "BIGINT AUTO_INCREMENT"
		childID = "BIGINT AUTO_INCREMENT"
	}
	script := fmt.Sprintf(`CREATE TABLE %s (%s %s NOT NULL, %s VARCHAR(40) NOT NULL DEFAULT 'semi;colon', PRIMARY KEY(%s,%s));
CREATE TABLE %s (%s %s PRIMARY KEY, %s BIGINT NOT NULL DEFAULT 1, %s VARCHAR(40) NOT NULL DEFAULT 'semi;colon', %s DECIMAL(12,4) NOT NULL DEFAULT 12.3456 CHECK(%s>=0), %s VARCHAR(40) DEFAULT 'omitted', %s VARCHAR(20), %s DECIMAL(12,4) GENERATED ALWAYS AS (%s*2) STORED, CONSTRAINT %s FOREIGN KEY(%s,%s) REFERENCES %s(%s,%s));
CREATE UNIQUE INDEX %s ON %s(%s,%s,%s);`,
		q("order.key"), q("B"), identity, q("A"), q("B"), q("A"),
		q("select"), q("ID"), childID, q("ParentB"), q("ParentA"), q("Amount"), q("Amount"), q("optional"), q("quoted\"name"), q("computed"), q("Amount"), q("parent.fk"), q("ParentB"), q("ParentA"), q("order.key"), q("B"), q("A"),
		q("Index.with.dot"), q("select"), q("ParentB"), q("ParentA"), q("Amount"))
	_, err := schema.ApplySQL(ctx, source, script, schema.ApplyOptions{Dialect: d, Atomic: pg})
	require.NoError(t, err)
	opts := schema.ExtractOptions{Schema: sourceSchema, Tables: []string{"select"}, IncludeDependencies: true}
	artifact, err := schema.Extract(ctx, source, opts)
	require.NoError(t, err)
	require.True(t, artifact.Complete)
	_, err = schema.Apply(ctx, target, artifact, schema.ApplyOptions{Atomic: pg})
	require.NoError(t, err)
	opts.Schema = targetSchema
	restored, err := schema.Extract(ctx, target, opts)
	require.NoError(t, err)
	require.Equal(t, artifact.SQL(), restored.SQL())
	for _, db := range []*sql.DB{source, target} {
		defaults := " DEFAULT VALUES"
		if !pg {
			defaults = " () VALUES ()"
		}
		_, err = db.ExecContext(ctx, "INSERT INTO "+q("order.key")+defaults)
		require.NoError(t, err)
		_, err = db.ExecContext(ctx, "INSERT INTO "+q("select")+defaults)
		require.NoError(t, err)
		var id int64
		var amount, computed float64
		var optional sql.NullString
		query := fmt.Sprintf("SELECT %s,%s,%s,%s FROM %s", q("ID"), q("Amount"), q("computed"), q("optional"), q("select"))
		require.NoError(t, db.QueryRowContext(ctx, query).Scan(&id, &amount, &computed, &optional))
		require.EqualValues(t, 1, id)
		require.Equal(t, 12.3456, amount)
		require.Equal(t, 24.6912, computed)
		require.Equal(t, "omitted", optional.String)
		_, err = db.ExecContext(ctx, "INSERT INTO "+q("select")+"("+q("ParentB")+") VALUES(9)")
		require.Error(t, err)
		_, err = db.ExecContext(ctx, "INSERT INTO "+q("select")+defaults)
		require.Error(t, err)
		_, err = db.ExecContext(ctx, "INSERT INTO "+q("select")+"("+q("Amount")+") VALUES(-1)")
		require.Error(t, err)
		_, err = db.ExecContext(ctx, "INSERT INTO "+q("select")+"("+q("Amount")+","+q("optional")+") VALUES(0,NULL)")
		require.NoError(t, err)
		require.NoError(t, db.QueryRowContext(ctx, "SELECT "+q("optional")+" FROM "+q("select")+" WHERE "+q("Amount")+"=0").Scan(&optional))
		require.False(t, optional.Valid)
	}
	// Counter state is a separate, opt-in part of extraction. Recreate only our
	// isolated target objects, restore state, then exercise the next generated IDs.
	opts.Schema = sourceSchema
	opts.IncludeSequenceState = true
	withState, err := schema.Extract(ctx, source, opts)
	require.NoError(t, err)
	for i := len(artifact.Tables) - 1; i >= 0; i-- {
		_, err = target.ExecContext(ctx, "DROP TABLE "+q(artifact.Tables[i]))
		require.NoError(t, err)
	}
	_, err = schema.Apply(ctx, target, withState, schema.ApplyOptions{Dialect: d, Atomic: pg})
	require.NoError(t, err)
	opts.Schema = targetSchema
	stateRestored, err := schema.Extract(ctx, target, opts)
	require.NoError(t, err)
	require.Equal(t, withState.SQL(), stateRestored.SQL())
	_, err = target.ExecContext(ctx, "INSERT INTO "+q("order.key")+"("+q("B")+") VALUES(1)")
	require.NoError(t, err)
	var next []int64
	for _, db := range []*sql.DB{source, target} {
		_, err = db.ExecContext(ctx, "INSERT INTO "+q("select")+"("+q("Amount")+") VALUES(1)")
		require.NoError(t, err)
		var id int64
		require.NoError(t, db.QueryRowContext(ctx, "SELECT "+q("ID")+" FROM "+q("select")+" WHERE "+q("Amount")+"=1").Scan(&id))
		next = append(next, id)
	}
	require.Equal(t, next[0], next[1])
	cycleSQL := fmt.Sprintf("CREATE TABLE %s(id BIGINT PRIMARY KEY,other_id BIGINT); CREATE TABLE %s(id BIGINT PRIMARY KEY,other_id BIGINT,CONSTRAINT cycle_b_fk FOREIGN KEY(other_id) REFERENCES %s(id)); ALTER TABLE %s ADD CONSTRAINT cycle_a_fk FOREIGN KEY(other_id) REFERENCES %s(id);", q("cycle.a"), q("cycle.b"), q("cycle.a"), q("cycle.a"), q("cycle.b"))
	_, err = schema.ApplySQL(ctx, source, cycleSQL, schema.ApplyOptions{Dialect: d, Atomic: pg})
	require.NoError(t, err)
	opts.Schema = sourceSchema
	opts.Tables = []string{"cycle.a"}
	opts.IncludeSequenceState = false
	cyclic, err := schema.Extract(ctx, source, opts)
	if pg {
		require.NoError(t, err)
		_, err = schema.Apply(ctx, target, cyclic, schema.ApplyOptions{Dialect: d, Atomic: true})
		require.NoError(t, err)
		for _, db := range []*sql.DB{source, target} {
			_, err = db.ExecContext(ctx, "INSERT INTO "+q("cycle.a")+"(id) VALUES(1)")
			require.NoError(t, err)
			_, err = db.ExecContext(ctx, "INSERT INTO "+q("cycle.b")+"(id,other_id) VALUES(1,1)")
			require.NoError(t, err)
			_, err = db.ExecContext(ctx, "UPDATE "+q("cycle.a")+" SET other_id=1 WHERE id=1")
			require.NoError(t, err)
			_, err = db.ExecContext(ctx, "UPDATE "+q("cycle.a")+" SET other_id=9 WHERE id=1")
			require.Error(t, err)
		}
	} else {
		require.ErrorIs(t, err, schema.ErrUnsupported)
		require.False(t, cyclic.Complete)
	}
}
